import { expect, test } from "bun:test"
import { mkdir, mkdtemp, rm, stat, utimes, writeFile } from "node:fs/promises"
import path from "node:path"
import os from "node:os"
import { brotliCompressSync } from "node:zlib"
import { publicBuildAssetProof, writePublicBuildManifest } from "./public-build-assets"
import { canCacheBuildAsset, PUBLIC_BUILD_ASSET_HEADER } from "../shared/public-asset-cache"

test("only generated allowlisted bytes and their verified encoded representations receive an asset proof", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "stillon-public-build-"))
  try {
    await mkdir(path.join(root, "assets"))
    const name = "assets/index-aaaaaaaaaaaa.js", privateName = "assets/notes-bbbbbbbbbbbb.txt"
    await writeFile(path.join(root, name), "export const ready=true")
    await writeFile(path.join(root, name + ".br"), brotliCompressSync("export const ready=true"))
    await writeFile(path.join(root, privateName), "not generated by the application build")
    expect(await publicBuildAssetProof(root, name, "identity")).toBeNull()
    await writePublicBuildManifest(root, [name])
    expect(await publicBuildAssetProof(root, name, "identity")).toMatch(/^[a-f0-9]{64}:[a-f0-9]{64}$/u)
    expect(await publicBuildAssetProof(root, name, "br")).toMatch(/^[a-f0-9]{64}:[a-f0-9]{64}$/u)
    expect(await publicBuildAssetProof(root, privateName, "identity")).toBeNull()
    await writeFile(path.join(root, name + ".br"), "changed encoded bytes")
    expect(await publicBuildAssetProof(root, name, "br")).toBeNull()
    await writeFile(path.join(root, name), "changed application bytes")
    expect(await publicBuildAssetProof(root, name, "identity")).toBeNull()
  } finally { await rm(root, { recursive: true, force: true }) }
})

test("a build switch invalidates the old allowlist; missing manifests fail closed", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "stillon-public-build-switch-"))
  try {
    await mkdir(path.join(root, "assets"))
    const first = "assets/index-aaaaaaaaaaaa.js", second = "assets/index-bbbbbbbbbbbb.js"
    await writeFile(path.join(root, first), "export const build=1")
    await writeFile(path.join(root, second), "export const build=2")
    const old = await writePublicBuildManifest(root, [first])
    expect(await publicBuildAssetProof(root, first, "identity")).toStartWith(old.build)
    const current = await writePublicBuildManifest(root, [second])
    expect(current.build).not.toBe(old.build)
    expect(await publicBuildAssetProof(root, first, "identity")).toBeNull()
    expect(await publicBuildAssetProof(root, second, "identity")).toStartWith(current.build)
    await rm(path.join(root, "public-build-assets.json"))
    expect(await publicBuildAssetProof(root, second, "identity")).toBeNull()
  } finally { await rm(root, { recursive: true, force: true }) }
})

test("same-length asset replacement never reuses a proof based only on file metadata", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "stillon-public-build-mutation-"))
  try {
    await mkdir(path.join(root, "assets"))
    const name = "assets/index-aaaaaaaaaaaa.js", file = path.join(root, name)
    await writeFile(file, "export const ready=true")
    await writePublicBuildManifest(root, [name])
    expect(await publicBuildAssetProof(root, name, "identity")).not.toBeNull()
    const before = await stat(file)
    await writeFile(file, "export const ready=null")
    await utimes(file, before.atime, before.mtime)
    expect((await stat(file)).size).toBe(before.size)
    expect(await publicBuildAssetProof(root, name, "identity")).toBeNull()
  } finally { await rm(root, { recursive: true, force: true }) }
})

test("relay caching requires a validated build proof and excludes APIs, previews, cookies and partial bodies", () => {
  const headers = new Headers({ "Cache-Control": "public, max-age=31536000, immutable", [PUBLIC_BUILD_ASSET_HEADER]: "a".repeat(64) + ":" + "b".repeat(64) })
  const request = new Request("https://h-example.stillon.example/assets/index-aaaaaaaaaaaa.js")
  expect(canCacheBuildAsset(request, 200, headers, false)).toBe(true)
  expect(canCacheBuildAsset(request, 304, headers, false)).toBe(true)
  expect(canCacheBuildAsset(request, 206, headers, false)).toBe(false)
  expect(canCacheBuildAsset(request, 200, headers, true)).toBe(false)
  for (const route of ["/", "/index.html", "/api/projects/workspace/preview/index-aaaaaaaaaaaa.js", "/api/preview-targets/target/content", "/assets/arbitrary.js"]) {
    expect(canCacheBuildAsset(new Request("https://h-example.stillon.example" + route), 200, headers, false)).toBe(false)
  }
  headers.set("Set-Cookie", "private=sample")
  expect(canCacheBuildAsset(request, 200, headers, false)).toBe(false)
  headers.delete("Set-Cookie"); headers.delete(PUBLIC_BUILD_ASSET_HEADER)
  expect(canCacheBuildAsset(request, 200, headers, false)).toBe(false)
})
